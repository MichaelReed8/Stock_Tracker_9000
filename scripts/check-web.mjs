import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4173/');
  await page.getByRole('heading', { name: 'The daily movers.' }).waitFor();
  assert.equal(await page.locator('.app-shell').evaluate(el => getComputedStyle(el).display), 'grid');
  await mkdir('.aws-sam/preview', { recursive: true });
  await page.screenshot({ path: '.aws-sam/preview/desktop.png', fullPage: true });
  assert.equal(await page.locator('.stock-row').count(), 5);
  await page.locator('.stock-row').first().click();
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.getByRole('link', { name: 'Research on Yahoo Finance' }).count(), 1);
  await page.getByRole('button', { name: 'Close stock details' }).click();
  await page.getByRole('button', { name: /Losers/ }).click();
  assert.match(await page.locator('.stock-row').first().innerText(), /-/);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: '.aws-sam/preview/mobile.png', fullPage: true });
  await page.getByRole('button', { name: /View coverage/ }).click();
  await page.getByRole('heading', { name: 'Behind the numbers.' }).waitFor();
  await page.getByRole('button', { name: 'Daily summary' }).click();
  const permanent = await page.locator('footer a').getAttribute('href');
  await page.goto('http://127.0.0.1:4173' + permanent);
  await page.getByRole('heading', { name: 'The daily movers.' }).waitFor();
  const saved = await page.evaluate(async () => (await fetch('/api/summaries/latest')).json());
  const authPage = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await authPage.route('**/api/config', route => route.fulfill({ json: { region: 'ca-central-1', clientId: 'test-client' } }));
  await authPage.route('https://cognito-idp.ca-central-1.amazonaws.com/', async route => {
    const operation = route.request().headers()['x-amz-target'];
    await route.fulfill({ json: operation.endsWith('InitiateAuth') ? { ChallengeName: 'NEW_PASSWORD_REQUIRED', Session: 'test-session' } : { AuthenticationResult: { AccessToken: 'test-access', RefreshToken: 'test-refresh' } } });
  });
  await authPage.route('**/api/summaries/latest', route => route.fulfill({ json: saved }));
  await authPage.goto('http://127.0.0.1:4173/');
  await authPage.getByRole('heading', { name: 'Welcome back' }).waitFor();
  await authPage.screenshot({ path: '.aws-sam/preview/login.png', fullPage: true });
  await authPage.getByLabel('Email', { exact: true }).fill('browser-test@example.com');
  await authPage.getByLabel('Password', { exact: true }).fill('Test-Only-Not-A-Real-Password1');
  await authPage.getByRole('button', { name: 'Sign in' }).click();
  await authPage.getByRole('heading', { name: 'Choose your password' }).waitFor();
  await authPage.getByLabel(/^New password/).fill('Test-Only-New-Password1!');
  await authPage.getByRole('button', { name: 'Set password & sign in' }).click();
  await authPage.getByRole('heading', { name: 'The daily movers.' }).waitFor();
  await authPage.getByRole('button', { name: 'Sign out', exact: true }).filter({ visible: true }).click();
  await authPage.getByRole('heading', { name: 'Welcome back' }).waitFor();
  assert.equal(await authPage.evaluate(() => sessionStorage.getItem('stock-session')), null);
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('Desktop/mobile rendering, real saved movers, details, directions, coverage, immutable links, first-login password challenge, sign-out and no overflow passed. Auth interaction uses mocked Cognito, not real passwords.');
} finally { await browser.close(); }
